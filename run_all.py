"""Run every benchmark and write the scoreboard.

    python run_all.py            run all eight (B4 and B8 take a few minutes each)
    python run_all.py b1 b5      run only some
    python run_all.py --report   rebuild the scoreboard from saved results, no runs

Writes results/scoreboard.md (readable) and results/atlas_points.json (every
benchmark's place on the common axes, for the plots).
"""

import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
NAMES = [f"b{i}" for i in range(1, 9)]


def run(names):
    for n in names:
        t = time.time()
        print(f"\n=== {n.upper()} ===", flush=True)
        r = subprocess.run([sys.executable, str(ROOT / "benchmarks" / n / "run.py")])
        print(f"({n.upper()} finished in {time.time() - t:.0f} s, exit code {r.returncode})")


def fmt(x):
    if x is None:
        return "–"
    if isinstance(x, float):
        return f"{x:.3g}"
    return str(x)


def report():
    rows, points = [], []
    for n in NAMES:
        f = ROOT / "benchmarks" / n / "result.json"
        if not f.exists():
            rows.append(f"| {n.upper()} | (not run) | | | | |")
            continue
        d = json.loads(f.read_text())
        points += [dict(p, benchmark=d["benchmark"]) for p in d["atlas_points"]]
        first = True
        for c in d["checks"]:
            if c["measured"] is not None:
                target = fmt(c["measured"])
            else:
                lo, hi = c["measured_low"], c["measured_high"]
                target = (f"≥ {fmt(lo)}" if hi is None else
                          f"≤ {fmt(hi)}" if lo is None else f"{fmt(lo)}–{fmt(hi)}")
            label = f"**{d['benchmark']}** {d['title']} — **{d['overall']}**" if first else ""
            rows.append(f"| {label} | {c['name']} | {fmt(c['computed'])} | {target} | {c['unit']} | {c['status']} |")
            first = False
    scored = []
    for n in NAMES:
        f = ROOT / "benchmarks" / n / "result.json"
        if f.exists():
            scored.append(json.loads(f.read_text())["overall"])
    summary = {k: scored.count(k) for k in ("pass", "partial", "fail", "not computed")}
    text = ["# Scoreboard", "",
            "Generated by `run_all.py`. A check passes when the computed value is within 30% of the "
            "measured one (or of the nearer end of a range or bound). Rows marked *info* are "
            "sensitivity runs or side results and are not scored.", "",
            f"Benchmarks: {summary['pass']} pass, {summary['partial']} partial, "
            f"{summary['fail']} fail, {summary['not computed']} not computed.", "",
            "| Benchmark | Quantity | Computed | Measured | Unit | Status |",
            "|---|---|---|---|---|---|", *rows, ""]
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "scoreboard.md").write_text("\n".join(text))
    (ROOT / "results" / "atlas_points.json").write_text(json.dumps(points, indent=2) + "\n")
    print("\n".join(text))


if __name__ == "__main__":
    args = [a.lower() for a in sys.argv[1:]]
    if "--report" not in args:
        run([a for a in args if a in NAMES] or NAMES)
    report()
