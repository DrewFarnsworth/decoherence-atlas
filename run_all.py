"""Run every benchmark and write the scoreboard.

    python run_all.py            run all ten (B4 and B8 take a few minutes each)
    python run_all.py b1 b5      run only some
    python run_all.py --report   rebuild the scoreboard from saved results, no runs

Writes results/scoreboard.md (readable) and results/atlas_points.json (every
benchmark's place on the common axes, for the plots).
"""

import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# Windows consoles and files default to cp1252, which lacks symbols such as ≤ and ±.
# Write files as UTF-8 and never let printing stop a run.
for stream in (sys.stdout, sys.stderr):
    try:
        stream.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
NAMES = [f"b{i}" for i in range(1, 11)]


def run(names):
    for n in names:
        t = time.time()
        print(f"\n=== {n.upper()} ===", flush=True)
        r = subprocess.run([sys.executable, str(ROOT / "benchmarks" / n / "run.py")])
        print(f"({n.upper()} finished in {time.time() - t:.0f} s, exit code {r.returncode})")


def fmt(x):
    if x is None:
        return "–"
    if isinstance(x, float):
        if 1e3 <= abs(x) < 1e6:
            return f"{x:,.0f}"
        return f"{x:.3g}"
    return str(x)


def report():
    from atlas.scoring import K_SIGMA, NOTES, score
    rows, points, tally = [], [], {}
    for n in NAMES:
        f = ROOT / "benchmarks" / n / "result.json"
        if not f.exists():
            rows.append(f"| {n.upper()} | (not run) | | | | | | | |")
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        points += [dict(p, benchmark=d["benchmark"]) for p in d["atlas_points"]]
        first = True
        for c in d["checks"]:
            if c["measured"] is not None:
                target = fmt(c["measured"])
            else:
                lo, hi = c["measured_low"], c["measured_high"]
                target = (f"≥ {fmt(lo)}" if hi is None else
                          f"≤ {fmt(hi)}" if lo is None else f"{fmt(lo)}–{fmt(hi)}")
            status, rule, sign, tier = score(d["benchmark"], c)
            if tier != "info" and status in ("pass", "fail", "flag"):
                tally.setdefault(tier, {"pass": 0, "fail": 0, "flag": 0})[status] += 1
            label = f"**{d['benchmark']}** {d['title']}" if first else ""
            rows.append(f"| {label} | {c['name']} | {fmt(c['computed'])} | {target} | {c['unit']} | {tier} | {rule} | {sign} | {status} |")
            first = False
    per_tier = "; ".join(f"tier {t}: {v['pass']} pass, {v['fail']} fail, {v['flag']} flag" for t, v in sorted(tally.items(), key=lambda x: str(x[0])))
    text = ["# Scoreboard", "",
            "Generated by `run_all.py`; rules in `atlas/scoring.py`. Tier 1 compares the atlas with published theory, "
            "tier 2 published theory with experiment, tier 3 framework-specific predictions (none yet). "
            f"Where a measurement states an uncertainty, a row passes within {K_SIGMA:g} standard uncertainties; "
            "otherwise the 30% rule applies and the row says so. Bounds are hard: outside a bound but within 30% "
            "is a *flag*. Sign says whether computed decoherence is too strong or too weak. "
            "*Info* rows (true by construction, sensitivity runs, negative controls) are not scored.", "",
            f"Scored rows: {per_tier}.", "",
            "| Benchmark | Quantity | Computed | Measured | Unit | Tier | Rule | Sign | Status |",
            "|---|---|---|---|---|---|---|---|---|", *rows, "",
            "## Open fixes", ""] + [f"- **{b}:** {t}" for b, t in NOTES.items()] + [""]
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "scoreboard.md").write_text("\n".join(text), encoding="utf-8")
    (ROOT / "results" / "atlas_points.json").write_text(json.dumps(points, indent=2) + "\n", encoding="utf-8")
    print("\n".join(text))


if __name__ == "__main__":
    args = [a.lower() for a in sys.argv[1:]]
    if "--report" not in args:
        run([a for a in args if a in NAMES] or NAMES)
    report()
